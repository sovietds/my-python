unit_price=float(input("单价："))
sales_volume=float(input("销量："))
unit_material=float(input("单位材料成本："))
unit_labor=float(input("单位直接人工："))
fixed_cost=float(input("固定成本："))
tax_rate=float(input("企业所得税税率："))
revenue=unit_price*sales_volume
unit_variable_cost=unit_material+unit_labor
variable_cost=unit_variable_cost*sales_volume
total_cost=variable_cost+fixed_cost
profit=revenue-total_cost
gross_margin=profit/revenue*100
net_profit=profit*(1-tax_rate)
print(f"{"="*5}月度利润计算{"="*5}")
print(f"营业收入：{revenue:,.0f}元")
print(f"变动成本：{variable_cost:,.0f}元")
print(f"固定成本：{fixed_cost:,.0f}元")
print(f"总成本：{total_cost:,.0f}元")
print(f"利润：{profit:,.0f}元")
print(f"利润率：{gross_margin:,.1f}%")
print(f"企业所得税税率：{tax_rate*100:,.1f}%")
print(f"净利润：{net_profit:,.0f}元")